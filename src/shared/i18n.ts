function getSerbianPluralForm(n: number): "one" | "few" | "many" {
    const n100 = n % 100;
    const n10 = n % 10;
    if (n100 >= 5 && n100 <= 20) return "many";
    if (n10 === 1) return "one";
    if (n10 >= 2 && n10 <= 4) return "few";
    return "many";
}

function getEnglishPluralForm(n: number): "one" | "many" {
    return n === 1 ? "one" : "many";
}

